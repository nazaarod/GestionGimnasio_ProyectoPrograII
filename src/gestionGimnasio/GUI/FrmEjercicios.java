    private void configurarTabla() {
        DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{
                    "Identificacion",
                    "Nombre",
                    "Dificultad",
                    "Descripcion"
                }, 0
        ) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };

        tblEjercicios.setModel(modelo);
        tblEjercicios.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
    }

    private void cargarTabla() {
        DefaultTableModel modelo
                = (DefaultTableModel) tblEjercicios.getModel();

        modelo.setRowCount(0);

        for (Ejercicio ejercicio : DatosRep.EJERCICIOS.obtenerTodos()) {
            modelo.addRow(new Object[]{
                ejercicio.getIdentificacion(),
                ejercicio.getNombre(),
                ejercicio.getDificultad(),
                ejercicio.getDescripcion()
            }
            );
        }
    }

    private void cargarDificultades() {
        cmbDificultad.removeAllItems();
        cmbDificultad.addItem("Principiante");
        cmbDificultad.addItem("Intermedio");
        cmbDificultad.addItem("Avanzado");
    }

    private boolean validarCampos() {

        if (txtIdentificacion.getText().trim().isEmpty()) {
            JOptionPane.showConfirmDialog(
                    this,
                    "Debe ingresar el Identificacion"
            );

            txtIdentificacion.requestFocus();
            return false;
        }

        if (txtNombre.getText().trim().isEmpty()) {
            JOptionPane.showConfirmDialog(
                    this,
                    "Debe ingresar el nombre"
            );

            txtNombre.requestFocus();
            return false;
        }

        if (cmbDificultad.getSelectedIndex() < 0) {
            JOptionPane.showConfirmDialog(
                    this,
                    "Seleccione la dificultad.",
                    "Dato requerido",
                    JOptionPane.WARNING_MESSAGE
            );

            cmbDificultad.requestFocus();
            return false;
        }

        if (txtDescripcion.getText().trim().isEmpty()) {
            JOptionPane.showConfirmDialog(
                    this,
                    "Debe ingresar la Descripcion"
            );

            txtDescripcion.requestFocus();
            return false;
        }

        return true;
    }

    private void limpiarFormulario() {

        txtIdentificacion.setText("");
        txtNombre.setText("");

        if (cmbDificultad.getItemCount() > 0) {
            cmbDificultad.setSelectedIndex(0);
        }

        txtDescripcion.setText("");

        tblEjercicios.clearSelection();

        filaSeleccionada = -1;

        txtIdentificacion.requestFocus();
    }

    private Ejercicio crearEjercicioDesdeFormulario() {
        return new Ejercicio(
                txtIdentificacion.getText().trim(),
                txtNombre.getText().trim(),
                cmbDificultad.getSelectedItem().toString(),
                txtDescripcion.getText().trim()
        );
    }

    private void cargarEjercicioSeleccionado() {

        filaSeleccionada = tblEjercicios.getSelectedRow();

        if (filaSeleccionada < 0) {
            return;
        }

        Ejercicio ejercicio
                = DatosRep.EJERCICIOS.obtener(filaSeleccionada);

        if (ejercicio == null) {
            return;
        }

        txtIdentificacion.setText(
                ejercicio.getIdentificacion()
        );

        txtNombre.setText(
                ejercicio.getNombre()
        );

        cmbDificultad.setSelectedItem(
                ejercicio.getDificultad()
        );

        txtDescripcion.setText(
                ejercicio.getDescripcion()
        );
    }

