    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (!validarCampos()) {
            return;
        }

        Ejercicio ejercicio
                = crearEjercicioDesdeFormulario();

        DatosRep.EJERCICIOS.agregar(ejercicio);

        cargarTabla();
        limpiarFormulario();

        JOptionPane.showMessageDialog(
                this,
                "Ejercicio registrado correctamente"
        );
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed

        if (filaSeleccionada < 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione un ejercicio dentro de la tabla"
            );

            return;
        }

        if (!validarCampos()) {
            return;
        }

        Ejercicio ejercicioAct
                = crearEjercicioDesdeFormulario();

        boolean actualizado
                = DatosRep.EJERCICIOS.actualizar(
                        filaSeleccionada,
                        ejercicioAct
                );

        if (actualizado) {

            cargarTabla();
            limpiarFormulario();

            JOptionPane.showMessageDialog(
                    this,
                    "Ejercicio actualizado correctamente"
            );

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo actualizar el Ejercicio"
            );
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

        if (filaSeleccionada < 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione un Ejercicio dentro de la tabla"
            );

            return;
        }

        Ejercicio ejercicio
                = DatosRep.EJERCICIOS.obtener(
                        filaSeleccionada
                );

        if (ejercicio == null) {
            return;
        }

        int respuesta
                = JOptionPane.showConfirmDialog(
                        this,
                        "Desea eliminar el ejercicio "
                        + ejercicio.getNombre() + "?",
                        "Confirmar eliminacion",
                        JOptionPane.YES_NO_OPTION
                );

        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }

        boolean eliminado
                = DatosRep.EJERCICIOS.eliminar(
                        filaSeleccionada
                );

        if (eliminado) {

            cargarTabla();
            limpiarFormulario();

            JOptionPane.showMessageDialog(
                    this,
                    "Ejercicio eliminado correctamente"
            );

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo eliminar el Ejercicio"
            );
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

